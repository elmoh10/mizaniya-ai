export const transactionCreateSchema = z
  .object({
    title: z.string().min(1),
    amount: z.number().positive(),
    currency: z.enum(['EGP', 'USD', 'SAR', 'EUR']).default('EGP'),
    type: z.enum(['expense', 'income', 'transfer']),
    category: z.enum([
      'Food & Groceries',
      'Housing & Utilities',
      'Bills & Subscriptions',
      'Transport & Ride Apps',
      'Installments & Debt',
      'Health & Education',
      'Family & Allowances',
      'Shopping & Entertainment',
      'Emergency & Savings',
      'Income & Salary',
    ]),
    walletId: z.string().min(1),
    destinationWalletId: z.string().optional(),
    paymentMethod: z
      .enum([
        'InstaPay',
        'Vodafone Cash',
        'CIB Bank',
        'Fawry',
        'Cash',
        'Visa/Mastercard',
        'Valu',
        'B.TECH / Aman',
      ])
      .default('InstaPay'),
    date: z.string().default(() => new Date().toISOString().split('T')[0]),
    merchant: z.string().optional(),
    notes: z.string().optional(),
    receiptUrl: z.string().optional(),
    isDuplicate: z.boolean().optional(),
    aiTag: z.string().optional(),
    hasAnomaly: z.boolean().optional(),
  })
  .superRefine((data, ctx) => {
    if (data.type === 'transfer') {
      if (!data.destinationWalletId || data.destinationWalletId.trim() === '') {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: 'Destination wallet is required for transfer transactions.',
          path: ['destinationWalletId'],
        });
      } else if (data.destinationWalletId === data.walletId) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: 'Destination wallet must differ from source wallet.',
          path: ['destinationWalletId'],
        });
      }
    }
  });

